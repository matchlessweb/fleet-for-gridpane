// Proves scripts/dump-schema.sql on a real Postgres running in memory (PGlite):
// the query runs, it changes nothing, and one planted object of every kind
// comes back in the document. Touches no real database.
//
//   PGLITE_DIR=/path/with/node_modules node scripts/test-dump-schema.mjs
//
// Needs @electric-sql/pglite 0.5 or later (not a dependency of the app).
import { readFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath, pathToFileURL } from "node:url";

const here = dirname(fileURLToPath(import.meta.url));
const from = (p) => (process.env.PGLITE_DIR ? pathToFileURL(join(process.env.PGLITE_DIR, "node_modules/@electric-sql/pglite/dist", p)).href : `@electric-sql/pglite${p === "index.js" ? "" : "/" + p.replace(/\.js$/, "")}`);
const { PGlite } = await import(from("index.js"));
// DUMP_SQL points the proof at another copy of the query: a broken copy must fail.
const SQL = readFileSync(process.env.DUMP_SQL || join(here, "dump-schema.sql"), "utf8");
const db = new PGlite();

let ran = 0, failed = 0;
const check = (name, got, want) => {
  ran++;
  const ok = JSON.stringify(got) === JSON.stringify(want);
  if (!ok) failed++;
  console.log(`  ${ok ? "ok  " : "FAIL"} ${name}${ok ? "" : `\n       got  ${JSON.stringify(got)}\n       want ${JSON.stringify(want)}`}`);
};

await db.exec(`
  create role anon nologin; create role authenticated nologin; create role service_role nologin bypassrls;
  create schema auth; create table auth.users (id uuid primary key, email text);
  create type public.site_kind as enum ('live', 'staging');
  create table public.servers (
    id bigint generated by default as identity primary key,
    label text not null,
    ip inet,
    created_at timestamptz not null default now(),
    constraint servers_label_len check (char_length(label) <= 80)
  );
  comment on table public.servers is 'One row per server';
  comment on column public.servers.label is 'The name shown in the panel';
  create table public.sites (
    id bigint primary key,
    server_id bigint not null references public.servers (id) on delete cascade,
    url text not null,
    kind public.site_kind not null default 'live',
    url_lower text generated always as (lower(url)) stored,
    unique (server_id, url)
  );
  create index sites_url_idx on public.sites (url);
  create table public.notes (id serial primary key, body text);
  alter table public.sites enable row level security;
  create policy "signed-in people read sites" on public.sites for select to authenticated using (true);
  create policy "service writes sites" on public.sites for all to service_role using (true) with check (server_id > 0);
  grant select on public.sites to authenticated; grant all on public.sites to service_role;
  create function public.touch() returns trigger language plpgsql as $$ begin new.url := trim(new.url); return new; end $$;
  create trigger sites_touch before insert or update on public.sites for each row execute function public.touch();
  create function public.count_sites(p_server bigint) returns integer language sql security definer set search_path = public as $$ select count(*)::int from public.sites where server_id = p_server $$;
  revoke execute on function public.count_sites(bigint) from public; grant execute on function public.count_sites(bigint) to service_role;
  create function public.on_new_user() returns trigger language plpgsql as $$ begin return new; end $$;
  create trigger on_auth_user_created after insert on auth.users for each row execute function public.on_new_user();
  create view public.live_sites as select id, url from public.sites where kind = 'live';
  create publication supabase_realtime for table public.sites;
  insert into public.servers (label) values ('web1'); insert into public.sites (id, server_id, url) values (1, 1, 'https://shop.example.com/private-path');
`);

const count = async () => Number((await db.query("select (select count(*) from pg_class) + (select count(*) from public.sites) + (select count(*) from pg_proc) as n")).rows[0].n);
const before = await count();
let d;
try { d = (await db.query(SQL)).rows[0].dump; } catch (e) { console.log(`  FAIL the query runs\n       ${e.message.slice(0, 300)}`); console.log("dump-schema: 1 checks, 1 failed"); process.exit(1); }
check("the query runs and returns one document", typeof d, "object");
check("it changes nothing (objects, rows and functions counted before and after)", await count(), before);
check("it runs inside a read-only transaction", await db.exec("begin transaction read only").then(() => db.query(SQL)).then(() => db.exec("rollback")).then(() => "ok", (e) => e.message.slice(0, 80)), "ok");
check("no row's contents are in it", JSON.stringify(d).includes("private-path") || JSON.stringify(d).includes("web1"), false);

const table = (n) => d.tables.find((t) => t.name === n);
const col = (t, c) => table(t).columns.find((x) => x.name === c);
check("every table in public, and none from elsewhere", d.tables.map((t) => t.name), ["notes", "servers", "sites"]);
check("columns in their order", table("sites").columns.map((c) => c.name), ["id", "server_id", "url", "kind", "url_lower"]);
check("a column's type, not-null and default", [col("servers", "created_at").type, col("servers", "created_at").not_null, col("servers", "created_at").default], ["timestamp with time zone", true, "now()"]);
check("an identity column", col("servers", "id").identity, "d");
check("a serial column keeps its sequence default", /nextval\('.*notes_id_seq/.test(col("notes", "id").default), true);
check("its sequence is listed", d.sequences.some((s) => s.name === "notes_id_seq"), true);
check("a generated column and its expression", [col("sites", "url_lower").generated, col("sites", "url_lower").default], ["s", "lower(url)"]);
check("an enum column's type", col("sites", "kind").type, "site_kind");
check("the enum and its labels in order", d.enums.map((e) => [e.name, e.labels]), [["site_kind", ["live", "staging"]]]);
check("table and column comments", [table("servers").comment, col("servers", "label").comment], ["One row per server", "The name shown in the panel"]);
const cons = (t) => Object.fromEntries(table(t).constraints.map((k) => [k.type + ":" + k.name, k.def]));
check("a primary key", cons("sites")["p:sites_pkey"], "PRIMARY KEY (id)");
check("a foreign key with its delete rule", cons("sites")["f:sites_server_id_fkey"], "FOREIGN KEY (server_id) REFERENCES servers(id) ON DELETE CASCADE");
check("a unique constraint", cons("sites")["u:sites_server_id_url_key"], "UNIQUE (server_id, url)");
check("a check constraint", cons("servers")["c:servers_label_len"], "CHECK ((char_length(label) <= 80))");
check("an index of its own, and not the ones constraints made", table("sites").indexes.map((i) => i.name), ["sites_url_idx"]);
check("the index definition", table("sites").indexes[0].def, "CREATE INDEX sites_url_idx ON public.sites USING btree (url)");
check("row security on and off", [table("sites").rls, table("servers").rls], [true, false]);
const pol = (n) => table("sites").policies.find((p) => p.name === n);
check("a read policy: command, roles, condition", [pol("signed-in people read sites").cmd, pol("signed-in people read sites").roles, pol("signed-in people read sites").using], ["r", ["authenticated"], "true"]);
check("a write policy keeps its check", [pol("service writes sites").cmd, pol("service writes sites").roles, pol("service writes sites").check], ["*", ["service_role"], "(server_id > 0)"]);
check("grants to the three roles", table("sites").grants.filter((g) => g.role === "authenticated").map((g) => g.privilege), ["SELECT"]);
check("a trigger on a table", table("sites").triggers.map((t) => t.name), ["sites_touch"]);
check("the trigger's definition", /BEFORE INSERT OR UPDATE ON public\.sites FOR EACH ROW EXECUTE FUNCTION touch\(\)/.test(table("sites").triggers[0].def), true);
const fn = (n) => d.functions.find((f) => f.name === n);
check("every function in public", d.functions.map((f) => f.name), ["count_sites", "on_new_user", "touch"]);
check("a function's arguments, security and whole body", [fn("count_sites").args, fn("count_sites").security_definer, /SET search_path TO 'public'/.test(fn("count_sites").def) && fn("count_sites").def.includes("where server_id = p_server")], ["p_server bigint", true, true]);
check("who may run it", [/service_role=X/.test(fn("count_sites").acl), /^\{?=X|,=X/.test(fn("count_sites").acl)], [true, false]);
check("a trigger on another schema's table that calls our function", d.outside_triggers.map((t) => [t.table, t.name]), [["auth.users", "on_auth_user_created"]]);
check("a view and its definition", [d.views.map((v) => v.name), /FROM sites/.test(d.views[0].def) && /'live'::site_kind/.test(d.views[0].def)], [["live_sites"], true]);
check("tables published for live updates", d.publications.map((x) => [x.publication, x.table]), [["supabase_realtime", "sites"]]);
check("the server's version", /^\d+/.test(d.server_version), true);

console.log(`dump-schema: ${ran} checks, ${failed} failed`);
process.exit(failed ? 1 : 0);
