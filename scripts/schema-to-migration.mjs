// Writes the baseline migration from a capture of a working database's structure.
//
//   npm run schema:dump                          # a person runs this: it saves the capture outside the repository
//   node scripts/schema-to-migration.mjs         # -> supabase/migrations/<stamp>_baseline.sql and supabase/schema.snapshot.json
//   node scripts/schema-to-migration.mjs <capture.json>
//
// The baseline builds every table, constraint, index, access rule, grant,
// function, published table and scheduled job on an EMPTY Supabase project.
// scripts/test-baseline-migration.mjs proves it: it runs the baseline on a
// database in memory, captures that, and compares it with the snapshot.
//
// The snapshot is the same structure as data, so the proof needs no access to
// anyone's database. Neither file holds a row of data.
import { existsSync, mkdirSync, readFileSync, readdirSync, writeFileSync } from "node:fs";
import { homedir } from "node:os";
import { dirname, join, resolve } from "node:path";
import { fileURLToPath } from "node:url";
import { normalize, PLATFORM_FUNCTIONS } from "./lib-schema-normalize.mjs";

const root = resolve(dirname(fileURLToPath(import.meta.url)), "..");
const capture = resolve(process.argv[2] || join(process.env.XDG_CONFIG_HOME || join(homedir(), ".config"), "fleet/schema-dump.json"));
if (!existsSync(capture)) { console.error(`No capture at ${capture}. Make one with: npm run schema:dump`); process.exit(1); }
const d = JSON.parse(readFileSync(capture, "utf8"));
if (!Array.isArray(d.tables) || d.tables.length === 0) { console.error("The capture holds no tables. Nothing was written."); process.exit(1); }

const q = (name) => `"${String(name).replace(/"/g, '""')}"`;
const lit = (text) => `'${String(text).replace(/'/g, "''")}'`;
const t = (name) => `public.${q(name)}`;
const out = [];
const say = (...lines) => out.push(...lines);
const section = (title) => say("", `-- ── ${title} ${"─".repeat(Math.max(3, 72 - title.length))}`);
const CMD = { r: "select", a: "insert", w: "update", d: "delete", "*": "all" };
const ROLES = ["anon", "authenticated", "service_role"];

say(
  "-- The baseline: everything the dashboard's database holds, on an empty Supabase project.",
  "--",
  "-- Written by scripts/schema-to-migration.mjs from a capture of a working database's",
  "-- structure. Do not edit it by hand: change the database, capture it again, and",
  "-- write it again. scripts/test-baseline-migration.mjs proves this file builds the",
  "-- structure in supabase/schema.snapshot.json.",
  "--",
  "-- It expects what every Supabase project has: the roles anon, authenticated and",
  "-- service_role, and the schema `extensions`. Run it once, on a project with no",
  "-- tables of its own.",
);

section("extensions");
say("create extension if not exists pgcrypto with schema extensions;");
say("-- pg_cron runs the two clean-up jobs at the end of this file. Where it is not offered, they are skipped.");
say("do $do$ begin", "  if exists (select 1 from pg_available_extensions where name = 'pg_cron') then", "    create extension if not exists pg_cron;", "  end if;", "end $do$;");

// A serial column's sequence is made first; an identity column makes its own.
const owned = [];
for (const table of d.tables) for (const c of table.columns) {
  const m = /^nextval\('(?:public\.)?"?([^'"]+)"?'::regclass\)$/.exec(c.default || "");
  if (m) owned.push({ seq: m[1], table: table.name, column: c.name });
}
if (owned.length) {
  section("sequences");
  for (const o of owned) {
    const s = (d.sequences || []).find((x) => x.name === o.seq);
    say(`create sequence public.${q(o.seq)}${s && s.type !== "bigint" ? ` as ${s.type}` : ""};`);
  }
}

section("tables");
for (const table of d.tables) {
  const cols = table.columns.map((c) => {
    let line = `  ${q(c.name)} ${c.type}`;
    if (c.generated === "s") line += ` generated always as (${c.default}) stored`;
    else if (c.identity === "a") line += " generated always as identity";
    else if (c.identity === "d") line += " generated by default as identity";
    else if (c.default != null) line += ` default ${c.default}`;
    if (c.not_null) line += " not null";
    return line;
  });
  say(`create table ${t(table.name)} (`, cols.join(",\n"), ");");
  if (table.comment) say(`comment on table ${t(table.name)} is ${lit(table.comment)};`);
  for (const c of table.columns) if (c.comment) say(`comment on column ${t(table.name)}.${q(c.name)} is ${lit(c.comment)};`);
  say("");
}
for (const o of owned) say(`alter sequence public.${q(o.seq)} owned by ${t(o.table)}.${q(o.column)};`);

section("keys, checks and links between tables");
// Primary and unique keys first, so a link to another table always finds its key.
for (const kind of ["p", "u", "c", "f"]) for (const table of d.tables) for (const k of table.constraints.filter((x) => x.type === kind))
  say(`alter table ${t(table.name)} add constraint ${q(k.name)} ${k.def};`);

section("indexes");
for (const table of d.tables) for (const i of table.indexes) say(`${i.def};`);

section("functions");
const functions = d.functions.filter((f) => !PLATFORM_FUNCTIONS.has(f.name));
for (const f of functions) {
  say(`${f.def.trimEnd()};`);
  if (f.acl) {
    // The access list names who may run it: "role=X/grantor"; an empty role is everyone.
    const may = f.acl.replace(/^\{|\}$/g, "").split(",").map((e) => e.split("=")[0].replace(/^"|"$/g, "")).filter((r) => r !== "postgres");
    const sig = `public.${q(f.name)}(${f.args})`;
    say(`revoke all on function ${sig} from public, ${ROLES.join(", ")};`);
    if (may.length) say(`grant execute on function ${sig} to ${may.map((r) => (r === "" ? "public" : r)).join(", ")};`);
  }
  say("");
}

section("who may read and write each table");
for (const table of d.tables) {
  say(`alter table ${t(table.name)} ${table.rls ? "enable" : "disable"} row level security;`);
  if (table.rls_forced) say(`alter table ${t(table.name)} force row level security;`);
  // A new Supabase project hands every new table to all three roles; say exactly what each one gets instead.
  say(`revoke all on table ${t(table.name)} from ${ROLES.join(", ")};`);
  for (const role of ROLES) {
    const privileges = table.grants.filter((g) => g.role === role).map((g) => g.privilege.toLowerCase()).sort();
    if (privileges.length) say(`grant ${privileges.join(", ")} on table ${t(table.name)} to ${role};`);
  }
  for (const p of table.policies) {
    let line = `create policy ${q(p.name)} on ${t(table.name)}${p.permissive ? "" : " as restrictive"} for ${CMD[p.cmd]} to ${p.roles.join(", ")}`;
    if (p.using != null) line += ` using (${p.using})`;
    if (p.check != null) line += ` with check (${p.check})`;
    say(`${line};`);
  }
  say("");
}

if ((d.views || []).length || (d.enums || []).length || d.tables.some((x) => x.triggers.length) || (d.outside_triggers || []).length) {
  console.error("The capture holds a view, an enum or a trigger, which this writer does not write yet. Nothing was written.");
  process.exit(1);
}

if ((d.publications || []).length) {
  section("tables the app watches live");
  for (const p of d.publications) say(
    "do $do$ begin",
    `  if exists (select 1 from pg_publication where pubname = ${lit(p.publication)})`,
    `     and not exists (select 1 from pg_publication_tables where pubname = ${lit(p.publication)} and schemaname = 'public' and tablename = ${lit(p.table)}) then`,
    `    alter publication ${q(p.publication)} add table ${t(p.table)};`,
    "  end if;",
    "end $do$;");
}

if ((d.cron_jobs || []).length) {
  section("clean-up jobs");
  say("do $do$ begin", "  if exists (select 1 from pg_extension where extname = 'pg_cron') then");
  for (const j of d.cron_jobs) say(`    perform cron.schedule(${lit(j.name)}, ${lit(j.schedule)}, $job$${j.command}$job$);`);
  say("  end if;", "end $do$;");
}

const dir = join(root, "supabase/migrations");
mkdirSync(dir, { recursive: true });
const existing = readdirSync(dir).find((f) => /_baseline\.sql$/.test(f));
const file = join(dir, existing || "20261120000000_baseline.sql");
writeFileSync(file, out.join("\n") + "\n");
writeFileSync(join(root, "supabase/schema.snapshot.json"), JSON.stringify(normalize(d), null, 1) + "\n");
const n = normalize(d);
console.log(`Wrote ${file.replace(root + "/", "")} (${out.length} lines) and supabase/schema.snapshot.json`);
console.log(`  ${n.tables.length} tables, ${n.tables.reduce((a, x) => a + x.columns.length, 0)} columns, ${n.tables.reduce((a, x) => a + x.constraints.length, 0)} constraints, ${n.tables.reduce((a, x) => a + x.indexes.length, 0)} indexes, ${n.tables.reduce((a, x) => a + x.policies.length, 0)} access rules, ${n.functions.length} functions, ${n.publications.length} published tables, ${n.cron_jobs.length} scheduled jobs`);
const left = d.functions.filter((f) => PLATFORM_FUNCTIONS.has(f.name)).map((f) => f.name);
if (left.length) console.log(`  left out, because the platform adds it itself: ${left.join(", ")}`);
